const ENTRY_BY_QID = new Map(TITLE_PREDICATES.map((e) => [e.qid, e]));

/** @param {readonly string[]} p31 */
export const isChemicalElement = (p31) => p31.includes(CHEMICAL_ELEMENT);

/**
 * その項目の title に足す述語。無ければ null。
 * @param {readonly string[]} p31
 * @param {(qid: string) => boolean} isEventClass 出来事の P31 かどうか（classify.mjs の isMappedClass）
 * @returns {Predicate | null}
 */
export const predicateFor = (p31, isEventClass) => {
  if (p31.some(isEventClass)) return null;
  const hits = p31.flatMap((qid) => ENTRY_BY_QID.get(qid) ?? []);
  const strong = hits.filter((e) => !e.weak);
  const deciding = strong.length > 0 ? strong : hits;
  return PREDICATE_PRIORITY.find((p) => deciding.some((e) => e.predicate === p)) ?? null;
};

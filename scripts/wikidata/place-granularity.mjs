// 場所の粒度の表（人が編集する表）。場所の項目（P276 / P189 / P159 などの先）の P31 → 粒度。
//
// 戦争の P276 や、発見地・原産国には、国・大陸・海洋のような広い範囲の項目が入っていることが多く、
// その代表点にマーカーを置くと、意味のない場所（国の重心、大西洋の真ん中）に出来事が出てしまう。
// そこで場所を4段階に分け、粗いものは使わない（使い方は analyze.mjs / build-app-data.mjs）:
//   fine    … 都市・町・建物・遺跡・戦場など。そのまま使う
//   region  … 州・県・地方・島・海・川など。fine が無ければ使う
//   country … 国・国家（現存・過去とも）。fine / region があれば外し、country しか無ければ placeKind: "none"
//   coarse  … 大陸・海洋・世界など。常に外す
//
// - p31-domain-map.mjs と同じく、見るのは場所の項目の「直接の P31」だけ。P279（上位クラス）は辿らない。
// - 表にあるのは region / country / coarse のクラスだけ。どれにも当たらない場所は fine として扱う
//   （場所の項目の大半は都市や建物で、その種類は数百あり、列挙しきれないため）。
//   このため、表に無い「広い範囲」のクラスは fine として通ってしまう。REPORT ではなく build-app-data.mjs の出力に、
//   fine と判定された場所のクラスの上位が出るので、そこから足していく。
// - 1つの場所が複数の P31 を持つときは、いちばん粗いものを採る（「都市」かつ「主権国家」のシンガポールは country）。
//   ただし、都市のクラス（下の CITY_CLASSES）を持つ場所では、政治的な領域・行政区画のクラス（表で yieldsToCity: true のもの）を数えない（R4e-2）。
//   理由: 大都市の項目は、都市であると同時に行政区画や政治的な単位でもあることが多い（ロンドン = political territorial entity、
//   モスクワ = ロシアの連邦構成主体、ベルリン・ハンブルク = ドイツの州、ストラスブール = 神聖ローマ帝国の領邦）。
//   「いちばん粗いもの」だけで決めると、都市が country / region になり、country なら zoom 4 以上で地図から消える。
//   国家のクラス（主権国家、歴史的な国、王国、帝国、属領など）と、地形・水域・文化的な地域のクラスは、都市に譲らない
//   （シンガポール・モナコ・バチカン・香港は country のまま。都市国家 city-state は都市のクラスに入れていない）。
// - QID と英語ラベルは data/raw/app/place-class-labels.json（wbgetentities で取得）から機械的に転記した。


/** @type {ReadonlyMap<string, GranularityEntry>} */
const ENTRY_BY_QID = new Map(PLACE_GRANULARITY.map((e) => [e.qid, e]));

/**
 * 場所の項目の P31 から粒度を決める。どのクラスも表に無ければ fine。複数あれば、いちばん粗いもの。
 * ただし、都市のクラス（CITY_CLASSES）を持つ場所では、yieldsToCity のクラス（行政区画・政治的な領域）を数えない。
 * @param {readonly string[]} p31
 * @returns {Granularity}
 */
export const granularityOf = (p31) => {
  const isCity = p31.some((qid) => CITY_CLASSES.has(qid));
  const hits = p31.flatMap((qid) => {
    const entry = ENTRY_BY_QID.get(qid);
    return entry && !(isCity && entry.yieldsToCity) ? [entry.granularity] : [];
  });
  return COARSEST_FIRST.find((g) => hits.includes(g)) ?? "fine";
};

/**
 * 都市のクラスがあるために、行政区画・政治的な領域のクラスを数えなかった場所か（R4e-2 の規則が効いた場所）。
 * ロンドンやモスクワのような、都市であると同時に広い行政区画でもある場所。粒度は fine だが、建物や区のような「本当に細かい」場所より粗いので、
 * places の並び（ラベルを付ける先頭の点を決める）では、ほかの fine の後ろ、region の前に置く（analyze.mjs）。
 * @param {readonly string[]} p31
 */
export const isCityOverRegion = (p31) =>
  p31.some((qid) => CITY_CLASSES.has(qid)) && p31.some((qid) => ENTRY_BY_QID.get(qid)?.yieldsToCity === true);
